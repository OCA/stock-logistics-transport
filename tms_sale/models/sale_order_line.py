    def _compute_allowed_rate_card_ids(self):
        cards = self.env["tms.rate.card"]
        for line in self:
            mode = line._tms_transport_mode()
            booking = line._tms_booking_type()
            if not mode or not booking:
                line.allowed_rate_card_ids = cards
                continue
            partner_ids = [False]
            partner = line.order_id.partner_id
            if partner:
                partner_ids.extend((partner | partner.commercial_partner_id).ids)
            company = line.company_id or line.order_id.company_id
            transport_type = line.product_id.product_tmpl_id.transport_type
            line.allowed_rate_card_ids = cards.search(
                [
                    ("transport_type", "=", transport_type),
                    ("transit_mode", "=", mode),
                    ("booking_type", "=", booking),
                    ("partner_id", "in", partner_ids),
                    (
                        "company_id",
                        "in",
                        [False, company.id] if company else [False],
                    ),
                ]
            )

